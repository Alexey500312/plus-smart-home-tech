CREATE SCHEMA IF NOT EXISTS DELIVERY;

CREATE TABLE IF NOT EXISTS DELIVERY.ADDRESSES
(
  ID BIGINT GENERATED BY DEFAULT AS IDENTITY,
  COUNTRY VARCHAR(100),
  CITY VARCHAR(100),
  STREET VARCHAR(100),
  HOUSE VARCHAR(100),
  FLAT VARCHAR(100),
  CONSTRAINT PK_ADDRESSES PRIMARY KEY (ID)
);
COMMENT ON TABLE DELIVERY.ADDRESSES IS 'Содержит информацию о адресах';
COMMENT ON COLUMN DELIVERY.ADDRESSES.ID IS 'Уникальный идентификатор';
COMMENT ON COLUMN DELIVERY.ADDRESSES.COUNTRY IS 'Страна';
COMMENT ON COLUMN DELIVERY.ADDRESSES.CITY IS 'Город';
COMMENT ON COLUMN DELIVERY.ADDRESSES.STREET IS 'Улица';
COMMENT ON COLUMN DELIVERY.ADDRESSES.HOUSE IS 'Дом';
COMMENT ON COLUMN DELIVERY.ADDRESSES.FLAT IS 'Квартира';

CREATE TABLE IF NOT EXISTS DELIVERY.DELIVERIES
(
  ID UUID NOT NULL,
  STATE VARCHAR(20) NOT NULL,
  ORDERID UUID NOT NULL,
  ADDRESS_FROM BIGINT NOT NULL REFERENCES DELIVERY.ADDRESSES (ID) ON DELETE CASCADE,
  ADDRESS_TO BIGINT NOT NULL REFERENCES DELIVERY.ADDRESSES (ID) ON DELETE CASCADE,
  WEIGHT_TOTAL DOUBLE PRECISION,
  VOLUME_TOTAL DOUBLE PRECISION,
  FRAGILE BOOLEAN,
  CONSTRAINT PK_DELIVERIES PRIMARY KEY (ID)
);
COMMENT ON TABLE DELIVERY.DELIVERIES IS 'Содержит информацию о доставках';
COMMENT ON COLUMN DELIVERY.DELIVERIES.ID IS 'Уникальный идентификатор';
COMMENT ON COLUMN DELIVERY.DELIVERIES.STATE IS 'Статус доставки';
COMMENT ON COLUMN DELIVERY.DELIVERIES.ORDERID IS 'ИД заказа';
COMMENT ON COLUMN DELIVERY.DELIVERIES.ADDRESS_FROM IS 'ИД адреса склада';
COMMENT ON COLUMN DELIVERY.DELIVERIES.ADDRESS_TO IS 'ИД адреса назначения';
COMMENT ON COLUMN DELIVERY.DELIVERIES.WEIGHT_TOTAL IS 'Общий вес доставки';
COMMENT ON COLUMN DELIVERY.DELIVERIES.VOLUME_TOTAL IS 'Общий объём доставки';
COMMENT ON COLUMN DELIVERY.DELIVERIES.FRAGILE IS 'Признак хрупкости заказа';