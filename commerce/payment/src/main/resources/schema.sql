CREATE SCHEMA IF NOT EXISTS PAYMENT;

CREATE TABLE IF NOT EXISTS PAYMENT.PAYMENTS
(
  ID UUID NOT NULL,
  ORDERID UUID NOT NULL,
  STATE VARCHAR(50) NOT NULL,
  DELIVERY_TOTAL NUMERIC(12, 2),
  PRODUCT_TOTAL NUMERIC(12, 2),
  FEE_TOTAL NUMERIC(12, 2),
  TOTAL_PAYMENT NUMERIC(12, 2),
  CONSTRAINT PK_PAYMENTS PRIMARY KEY (ID)
);
COMMENT ON TABLE PAYMENT.PAYMENTS IS 'Содержит информацию о корзинах товаров';
COMMENT ON COLUMN PAYMENT.PAYMENTS.ID IS 'Уникальный идентификатор';
COMMENT ON COLUMN PAYMENT.PAYMENTS.ORDERID IS 'Имя пользователя';
COMMENT ON COLUMN PAYMENT.PAYMENTS.STATE IS 'Статус оплаты';
COMMENT ON COLUMN PAYMENT.PAYMENTS.DELIVERY_TOTAL IS 'Стоимост доставки';
COMMENT ON COLUMN PAYMENT.PAYMENTS.PRODUCT_TOTAL IS 'Стоимость товаров';
COMMENT ON COLUMN PAYMENT.PAYMENTS.FEE_TOTAL IS 'Стоимость НДС';
COMMENT ON COLUMN PAYMENT.PAYMENTS.TOTAL_PAYMENT IS 'Общая стоимость';