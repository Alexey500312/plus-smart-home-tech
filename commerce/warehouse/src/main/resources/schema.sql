CREATE SCHEMA IF NOT EXISTS WAREHOUSE;

CREATE TABLE IF NOT EXISTS WAREHOUSE.PRODUCTS
(
  ID UUID NOT NULL,
  WIDTH DOUBLE PRECISION NOT NULL,
  HEIGHT DOUBLE PRECISION NOT NULL,
  DEPTH DOUBLE PRECISION,
  WEIGHT DOUBLE PRECISION NOT NULL,
  FRAGILE BOOLEAN NOT NULL,
  QUANTITY INTEGER NOT NULL,
  CONSTRAINT PK_PRODUCTS PRIMARY KEY (ID)
);
COMMENT ON TABLE WAREHOUSE.PRODUCTS IS 'Содержит информацию о товарах на складе';
COMMENT ON COLUMN WAREHOUSE.PRODUCTS.ID IS 'Уникальный идентификатор';
COMMENT ON COLUMN WAREHOUSE.PRODUCTS.WIDTH IS 'Наименование товара';
COMMENT ON COLUMN WAREHOUSE.PRODUCTS.HEIGHT IS 'Описание товара';
COMMENT ON COLUMN WAREHOUSE.PRODUCTS.DEPTH IS 'Ссылка на картинку во внешнем хранилище или SVG';
COMMENT ON COLUMN WAREHOUSE.PRODUCTS.WEIGHT IS 'Статус остатка товара';
COMMENT ON COLUMN WAREHOUSE.PRODUCTS.FRAGILE IS 'Статус товара';
COMMENT ON COLUMN WAREHOUSE.PRODUCTS.QUANTITY IS 'Количество товара';

CREATE TABLE IF NOT EXISTS WAREHOUSE.ORDER_BOOKINGS
(
  ID BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  ORDERID UUID NOT NULL UNIQUE,
  DELIVERYID UUID,
  CONSTRAINT PK_ORDER_BOOKING PRIMARY KEY (ID)
);
COMMENT ON TABLE WAREHOUSE.ORDER_BOOKINGS IS 'Содержит информацию о бронировании для заказа';
COMMENT ON COLUMN WAREHOUSE.ORDER_BOOKINGS.ID IS 'Уникальный идентификатор';
COMMENT ON COLUMN WAREHOUSE.ORDER_BOOKINGS.ORDERID IS 'ИД заказа';
COMMENT ON COLUMN WAREHOUSE.ORDER_BOOKINGS.DELIVERYID IS 'ИД доставки';

CREATE TABLE IF NOT EXISTS WAREHOUSE.ORDER_BOOKING_PRODUCTS
(
  ID BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  BOOKINGID BIGINT NOT NULL REFERENCES WAREHOUSE.ORDER_BOOKINGS (ID) ON DELETE CASCADE,
  PRODUCTID UUID NOT NULL REFERENCES WAREHOUSE.PRODUCTS (ID) ON DELETE CASCADE,
  QUANTITY INTEGER NOT NULL,
  CONSTRAINT PK_ORDER_BOOKING_PRODUCTS PRIMARY KEY (ID)
);
COMMENT ON TABLE WAREHOUSE.ORDER_BOOKING_PRODUCTS IS 'Содержит информацию о забронированных товарах для заказа';
COMMENT ON COLUMN WAREHOUSE.ORDER_BOOKING_PRODUCTS.ID IS 'Уникальный идентификатор';
COMMENT ON COLUMN WAREHOUSE.ORDER_BOOKING_PRODUCTS.BOOKINGID IS 'ИД бронирования заказа';
COMMENT ON COLUMN WAREHOUSE.ORDER_BOOKING_PRODUCTS.PRODUCTID IS 'ИД товара';
COMMENT ON COLUMN WAREHOUSE.ORDER_BOOKING_PRODUCTS.QUANTITY IS 'Количество товара';
