CREATE SCHEMA IF NOT EXISTS ORDERS;

CREATE TABLE IF NOT EXISTS ORDERS.ADDRESSES
(
  ID BIGINT GENERATED BY DEFAULT AS IDENTITY,
  COUNTRY VARCHAR(100),
  CITY VARCHAR(100),
  STREET VARCHAR(100),
  HOUSE VARCHAR(100),
  FLAT VARCHAR(100),
  CONSTRAINT PK_ADDRESSES PRIMARY KEY (ID)
);
COMMENT ON TABLE ORDERS.ADDRESSES IS 'Содержит информацию о адресах';
COMMENT ON COLUMN ORDERS.ADDRESSES.ID IS 'Уникальный идентификатор';
COMMENT ON COLUMN ORDERS.ADDRESSES.COUNTRY IS 'Страна';
COMMENT ON COLUMN ORDERS.ADDRESSES.CITY IS 'Город';
COMMENT ON COLUMN ORDERS.ADDRESSES.STREET IS 'Улица';
COMMENT ON COLUMN ORDERS.ADDRESSES.HOUSE IS 'Дом';
COMMENT ON COLUMN ORDERS.ADDRESSES.FLAT IS 'Квартира';


CREATE TABLE IF NOT EXISTS ORDERS.ORDERS
(
  ID UUID NOT NULL,
  USERNAME VARCHAR(256) NOT NULL,
  ADDRESSID BIGINT NOT NULL REFERENCES ORDERS.ADDRESSES (ID) ON DELETE CASCADE,
  STATE VARCHAR(20) NOT NULL,
  SHOPPING_CARTID UUID NOT NULL,
  DELIVERYID UUID,
  PAYMENTID UUID,
  DELIVERY_WEIGHT DOUBLE PRECISION,
  DELIVERY_VOLUME DOUBLE PRECISION,
  FRAGILE BOOLEAN,
  TOTAL_PRICE NUMERIC(12, 2),
  DELIVERY_PRICE NUMERIC(12, 2),
  PRODUCT_PRICE NUMERIC(12, 2),
  CONSTRAINT PK_ORDERS PRIMARY KEY (ID)
);
COMMENT ON TABLE ORDERS.ORDERS IS 'Содержит информацию о заказах';
COMMENT ON COLUMN ORDERS.ORDERS.STATE IS 'Статус заказа';
COMMENT ON COLUMN ORDERS.ORDERS.SHOPPING_CARTID IS 'ИД корзины товаров';
COMMENT ON COLUMN ORDERS.ORDERS.DELIVERYID IS 'ИД доставки';
COMMENT ON COLUMN ORDERS.ORDERS.PAYMENTID IS 'ИД оплаты';
COMMENT ON COLUMN ORDERS.ORDERS.DELIVERY_WEIGHT IS 'Общий вес доставки';
COMMENT ON COLUMN ORDERS.ORDERS.DELIVERY_VOLUME IS 'Общий объём доставки';
COMMENT ON COLUMN ORDERS.ORDERS.FRAGILE IS 'Признак хрупкости заказа';
COMMENT ON COLUMN ORDERS.ORDERS.TOTAL_PRICE IS 'Общая стоимость';
COMMENT ON COLUMN ORDERS.ORDERS.DELIVERY_PRICE IS 'Стоимость доставки';
COMMENT ON COLUMN ORDERS.ORDERS.PRODUCT_PRICE IS 'Стоимость товаров в заказе';

CREATE TABLE IF NOT EXISTS ORDERS.ORDER_PRODUCTS
(
  ID BIGINT GENERATED BY DEFAULT AS IDENTITY,
  ORDERID UUID NOT NULL REFERENCES ORDERS.ORDERS (ID) ON DELETE CASCADE,
  PRODUCTID UUID NOT NULL,
  QUANTITY INTEGER NOT NULL,
  CONSTRAINT PK_ORDER_PRODUCTS PRIMARY KEY (ID)
);
COMMENT ON TABLE ORDERS.ORDER_PRODUCTS IS 'Содержит информацию товарах в корзине';
COMMENT ON COLUMN ORDERS.ORDER_PRODUCTS.ID IS 'Уникальный идентификатор';
COMMENT ON COLUMN ORDERS.ORDER_PRODUCTS.ORDERID IS 'Заказ';
COMMENT ON COLUMN ORDERS.ORDER_PRODUCTS.PRODUCTID IS 'Товар';
COMMENT ON COLUMN ORDERS.ORDER_PRODUCTS.QUANTITY IS 'Количество товара';